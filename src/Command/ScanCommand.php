<?php

declare(strict_types=1);

namespace Refit\Command;

use Refit\Explanations;
use Refit\Finding;
use Refit\Report;
use Refit\Report\HtmlReporter;
use Refit\Report\JsonReporter;
use Refit\Report\MarkdownReporter;
use Refit\Scanner;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Helper\Table;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

#[AsCommand(name: 'scan', description: 'Find what breaks on a newer PHP version and write a report. Changes nothing.')]
final class ScanCommand extends Command
{
    protected function configure(): void
    {
        Options::configure($this);
        $this
            ->addOption('html', null, InputOption::VALUE_REQUIRED, 'Write an HTML report to this file')
            ->addOption('markdown', null, InputOption::VALUE_REQUIRED, 'Write a Markdown report to this file')
            ->addOption('json', null, InputOption::VALUE_REQUIRED, 'Write a JSON report to this file (use --json=- for standard output)')
            ->addOption('php-binary', null, InputOption::VALUE_REQUIRED, 'PHP binary used to compile-check files (ideally the target version)', PHP_BINARY)
            ->addOption('no-branding', null, InputOption::VALUE_NONE, 'Leave the "Generated by Refit" footer out of reports')
            ->addOption('fail-on', null, InputOption::VALUE_REQUIRED, 'Exit with code 1 when the project\'s own code has issues of this level: breaks, review, deprecated or none', 'none');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);
        $path = Options::path($input);
        $target = Options::target($input);
        $failOn = (string) $input->getOption('fail-on');
        if (!in_array($failOn, ['breaks', 'review', 'deprecated', 'none'], true)) {
            throw new \InvalidArgumentException('--fail-on must be breaks, review, deprecated or none.');
        }
        $jsonToStdout = $input->getOption('json') === '-';
        $log = $jsonToStdout ? $io->getErrorStyle() : $io;

        $scanner = new Scanner(static fn (string $step) => $log->writeln('<comment>›</comment> ' . $step));
        $report = $scanner->scan(
            $path,
            $target,
            Options::minPhp($input, $target),
            (string) $input->getOption('php-binary'),
            (bool) $input->getOption('all-rules'),
            Options::excluded($input),
        );

        $branding = !$input->getOption('no-branding');
        if ($jsonToStdout) {
            $output->write((new JsonReporter())->render($report));
        } else {
            $this->summary($io, $report);
        }
        foreach (['html' => new HtmlReporter($branding), 'markdown' => new MarkdownReporter($branding), 'json' => new JsonReporter()] as $option => $reporter) {
            $file = $input->getOption($option);
            if ($file !== null && $file !== '-') {
                file_put_contents((string) $file, $reporter->render($report));
                $log->writeln(sprintf('Wrote %s report to <info>%s</info>', $option === 'html' ? 'HTML' : ucfirst($option), $file));
            }
        }

        return $this->exitCode($report, $failOn);
    }

    private function summary(SymfonyStyle $io, Report $report): void
    {
        $p = $report->project;
        $io->newLine();
        $io->writeln(sprintf('<options=bold>%s</> · %s%s · %d PHP files', $p->name, $p->type, $p->version ? ' ' . $p->version : '', count($p->phpFiles)));
        $io->writeln(sprintf('Target PHP %s · must keep running on PHP %s (%s)', $report->targetPhp, $report->minPhp, $report->minPhpSource));
        $io->newLine();

        $style = count($report->own(Finding::BREAKS)) > 0 ? 'error' : 'info';
        $io->writeln(sprintf('<%s>%s</%s>', $style, $report->verdict(), $style));
        $io->newLine();

        $table = new Table($io);
        $table->setHeaders(['', 'Your code', 'Bundled libraries']);
        foreach ([Finding::BREAKS, Finding::REVIEW, Finding::DEPRECATED] as $severity) {
            $table->addRow([Explanations::severityLabel($severity), count($report->own($severity)), count($report->bundled($severity))]);
        }
        $table->addRow(['Auto-fixable', $report->fixableCount(), '-']);
        $table->render();

        $groups = Report::group($report->own());
        if ($groups !== []) {
            $io->newLine();
            $rows = [];
            foreach (array_slice($groups, 0, 12) as $group) {
                $fixable = count(array_filter($group['findings'], static fn (Finding $f): bool => $f->fixable));
                $rows[] = [Explanations::severityLabel($group['severity']), Explanations::title($group['code'], $group['findings'][0]), count($group['findings']), $fixable];
            }
            $issues = new Table($io);
            $issues->setHeaders(['Level', 'Issue', 'Found', 'Auto-fixable'])->setRows($rows)->render();
            if (count($groups) > 12) {
                $more = count($groups) - 12;
                $io->writeln(sprintf('…and %d more %s. Write a report with --html, --markdown or --json to see them all.', $more, $more === 1 ? 'kind of issue' : 'kinds of issue'));
            }
        }
        if ($report->fixableCount() > 0) {
            $io->newLine();
            $io->writeln(sprintf('Run <info>refit fix %s --php=%s</info> to apply the automatic fixes, then review the diff.', escapeshellarg($report->project->root), $report->targetPhp));
        }
    }

    private function exitCode(Report $report, string $failOn): int
    {
        $levels = match ($failOn) {
            'breaks' => [Finding::BREAKS],
            'review' => [Finding::BREAKS, Finding::REVIEW],
            'deprecated' => [Finding::BREAKS, Finding::REVIEW, Finding::DEPRECATED],
            default => [],
        };
        foreach ($levels as $level) {
            if ($report->own($level) !== []) {
                return Command::FAILURE;
            }
        }

        return Command::SUCCESS;
    }
}
