<?php

declare(strict_types=1);

namespace Refit\Report;

use Refit\Explanations;
use Refit\Finding;
use Refit\Report;

final class MarkdownReporter
{
    private const MAX_LOCATIONS = 15;

    public function __construct(private readonly bool $branding = true)
    {
    }

    public function render(Report $report): string
    {
        $p = $report->project;
        $out = [];
        $out[] = sprintf('# PHP %s upgrade report: %s', $report->targetPhp, $this->text($p->name));
        $out[] = '';
        $out[] = sprintf('%s%s · %d PHP files · checked %s', $p->type, $p->version ? ' ' . $this->text($p->version) : '', count($p->phpFiles), $report->generatedAt->format('Y-m-d'));
        $out[] = '';
        $out[] = '**' . $report->verdict() . '**';
        $out[] = '';
        $out[] = '| | Your code | Bundled libraries |';
        $out[] = '|---|---:|---:|';
        foreach ([Finding::BREAKS, Finding::REVIEW, Finding::DEPRECATED] as $severity) {
            $out[] = sprintf('| %s | %d | %d |', Explanations::severityLabel($severity), count($report->own($severity)), count($report->bundled($severity)));
        }
        $out[] = sprintf('| Fixed by `refit fix` | %d | not changed |', $report->fixableCount());
        $out[] = '';
        $out[] = '- **Breaks**: fails on PHP ' . $report->targetPhp . '. Visitors usually see a "critical error" page.';
        $out[] = '- **Check**: can fail depending on input; needs a person to look at it.';
        $out[] = '- **Deprecated**: still works, but logs notices and will break in a later PHP version.';
        $out[] = '';

        $groups = Report::group($report->own());
        if ($groups !== []) {
            $out[] = '## Issues in your code';
            $out[] = '';
            foreach ($groups as $group) {
                $this->group($out, $group, $report->targetPhp);
            }
        }

        $old = Report::group($report->preexisting());
        if ($old !== []) {
            $out[] = '## Already a problem on PHP ' . $report->minPhp;
            $out[] = '';
            $out[] = 'These already fail or log notices on PHP ' . $report->minPhp . ', the oldest version the project supports, so the upgrade does not change them. They are often in code that never runs, but some are real bugs.';
            $out[] = '';
            foreach ($old as $group) {
                $this->group($out, $group, $report->targetPhp);
            }
        }

        $libraries = LibrarySummary::rows($report);
        if ($libraries !== []) {
            $out[] = '## Bundled libraries';
            $out[] = '';
            $out[] = 'These folders hold third-party code. Update them to a release that supports PHP ' . $report->targetPhp . ' instead of patching them by hand; `refit fix` leaves them alone.';
            $out[] = '';
            $out[] = '| Library | Version | Folder | Breaks | Check | Deprecated |';
            $out[] = '|---|---|---|---:|---:|---:|';
            foreach ($libraries as $row) {
                $out[] = sprintf('| %s | %s | `%s` | %d | %d | %d |', $this->text($row['name']), $this->text($row['version'] ?? '?'), $this->text($row['path']), $row['breaks'], $row['review'], $row['deprecated']);
            }
            $out[] = '';
        }

        $out[] = '## How this was checked';
        $out[] = '';
        $out[] = sprintf('- Target: PHP %s. Oldest PHP the code must keep supporting: %s (%s); automatic fixes never use newer syntax than that.', $report->targetPhp, $report->minPhp, $report->minPhpSource);
        $out[] = sprintf('- Every file was compiled with PHP %s (`php -l`). No project code was executed.', $report->lintPhp);
        $out[] = '- Tools: ' . implode(', ', array_map(static fn (string $tool, string $version): string => $tool . ' ' . $version, array_keys($report->tools), $report->tools)) . '.';
        $out[] = '- Static checks cannot see problems that depend on runtime data, such as a function receiving null or a string where it now requires an array. Test the upgraded code on a staging site with debug logging on.';
        if ($this->branding) {
            $out[] = '';
            $out[] = '---';
            $out[] = 'Generated by [Refit](' . \Refit\Application::REPOSITORY_URL . '), free and open source. Need the upgrade done for you? [QiYuan Labs](https://php.qiyuanlabs.ai) does fixed-price PHP upgrades.';
        }

        return implode("\n", $out) . "\n";
    }

    /**
     * @param list<string> $out
     * @param array{code: string, severity: string, findings: list<Finding>} $group
     */
    private function group(array &$out, array $group, string $targetPhp): void
    {
        $findings = $group['findings'];
        $fixable = count(array_filter($findings, static fn (Finding $f): bool => $f->fixable));
        $out[] = sprintf('### %s · %s · %d found%s', Explanations::severityLabel($group['severity']), $this->text(Explanations::title($group['code'], $findings[0])), count($findings), $fixable > 0 ? sprintf(', %d auto-fixable', $fixable) : '');
        $out[] = '';
        $out[] = Explanations::meaning($group['code'], $group['severity'], $targetPhp);
        $fix = Explanations::fix($group['code']);
        if ($fix !== null) {
            $out[] = '';
            $out[] = 'Fix: ' . $fix;
        }
        $out[] = '';
        foreach (array_slice($findings, 0, self::MAX_LOCATIONS) as $finding) {
            $out[] = sprintf('- `%s:%d`%s %s', $this->text($finding->file), $finding->line, $finding->fixable ? ' (auto)' : '', $this->text($finding->message));
        }
        if (count($findings) > self::MAX_LOCATIONS) {
            $out[] = sprintf('- …and %d more (see the JSON report for all of them)', count($findings) - self::MAX_LOCATIONS);
        }
        $out[] = '';
    }

    private function text(string $value): string
    {
        return str_replace(['|', "\n", "\r", '`'], ['\\|', ' ', ' ', "'"], $value);
    }
}
