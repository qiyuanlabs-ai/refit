<?php

declare(strict_types=1);

namespace Refit\Report;

use Refit\Application;
use Refit\Explanations;
use Refit\Finding;
use Refit\Report;

/**
 * A single self-contained HTML page meant to be sent to a client or a plugin author.
 */
final class HtmlReporter
{
    private const MAX_LOCATIONS = 50;

    public function __construct(private readonly bool $branding = true)
    {
    }

    public function render(Report $report): string
    {
        $p = $report->project;
        $e = $this->e(...);
        $severityClass = count($report->own(Finding::BREAKS)) > 0 ? 'breaks' : (count($report->own(Finding::REVIEW)) > 0 ? 'review' : (count($report->own(Finding::DEPRECATED)) > 0 ? 'deprecated' : 'ok'));

        $stats = '';
        foreach ([Finding::BREAKS, Finding::REVIEW, Finding::DEPRECATED] as $severity) {
            $stats .= sprintf(
                '<div class="stat %s"><span class="num">%d</span><span class="label">%s</span><span class="sub">%d in bundled libraries</span></div>',
                $severity,
                count($report->own($severity)),
                $e(Explanations::severityLabel($severity)),
                count($report->bundled($severity)),
            );
        }
        $stats .= sprintf('<div class="stat fix"><span class="num">%d</span><span class="label">Auto-fixable</span><span class="sub">by <code>refit fix</code></span></div>', $report->fixableCount());

        $groups = '';
        foreach (Report::group($report->own()) as $group) {
            $groups .= $this->group($group, $report->targetPhp);
        }
        if ($groups === '') {
            $groups = '<p class="empty">No issues found in the project\'s own code.</p>';
        }

        $old = '';
        $oldGroups = Report::group($report->preexisting());
        if ($oldGroups !== []) {
            $old = '<h2>Already a problem on PHP ' . $e($report->minPhp) . '</h2><p>These already fail or log notices on PHP ' . $e($report->minPhp) . ', the oldest version the project supports, so the upgrade does not change them. They are often in code that never runs, but some are real bugs.</p>';
            foreach ($oldGroups as $group) {
                $old .= $this->group($group, $report->targetPhp);
            }
        }

        $libraries = '';
        $rows = LibrarySummary::rows($report);
        if ($rows !== []) {
            $libraries .= '<h2>Bundled libraries</h2><p>These folders hold third-party code. Update each one to a release that supports PHP ' . $e($report->targetPhp) . ' rather than patching it by hand; <code>refit fix</code> leaves them alone.</p>';
            $libraries .= '<div class="scroll"><table><thead><tr><th>Library</th><th>Version</th><th>Folder</th><th class="n">Breaks</th><th class="n">Check</th><th class="n">Deprecated</th></tr></thead><tbody>';
            foreach ($rows as $row) {
                $libraries .= sprintf('<tr><td>%s</td><td>%s</td><td><code>%s</code></td><td class="n">%d</td><td class="n">%d</td><td class="n">%d</td></tr>', $e($row['name']), $e($row['version'] ?? '?'), $e($row['path']), $row['breaks'], $row['review'], $row['deprecated']);
            }
            $libraries .= '</tbody></table></div>';
        }

        $tools = implode(', ', array_map(static fn (string $t, string $v): string => $t . ' ' . $v, array_keys($report->tools), $report->tools));
        $footer = $this->branding
            ? sprintf('<footer>Generated by <a href="%s">Refit</a>, free and open source. Need the upgrade done for you? <a href="https://php.qiyuanlabs.ai">QiYuan Labs</a> does fixed-price PHP upgrades.</footer>', $e(Application::REPOSITORY_URL))
            : '';

        return <<<HTML
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>PHP {$e($report->targetPhp)} report: {$e($p->name)}</title>
<style>
:root{--bg:#fbfaf8;--panel:#fff;--text:#1d1d1f;--muted:#5f6368;--line:#e4e2dd;--breaks:#b42318;--breaks-bg:#fef1f0;--review:#9a5b00;--review-bg:#fff6e5;--deprecated:#475467;--deprecated-bg:#f2f4f7;--fix:#067647;--fix-bg:#ecfdf3;--accent:#3c4fe0}
@media (prefers-color-scheme:dark){:root{--bg:#141416;--panel:#1c1c1f;--text:#ececef;--muted:#a0a0a8;--line:#2e2e33;--breaks:#ff8a7a;--breaks-bg:#3a1714;--review:#ffc266;--review-bg:#352610;--deprecated:#c3c8d0;--deprecated-bg:#26282d;--fix:#6ce0a6;--fix-bg:#10291d;--accent:#9aa6ff}}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:15px/1.55 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif}
main{max-width:920px;margin:0 auto;padding:32px 16px 48px}h1{font-size:26px;line-height:1.25;margin:0 0 4px}h2{font-size:19px;margin:36px 0 12px}
.meta{color:var(--muted);margin:0 0 20px}.verdict{padding:14px 16px;border-radius:10px;font-weight:600;margin-bottom:18px;border:1px solid var(--line)}
.verdict.breaks{background:var(--breaks-bg);color:var(--breaks)}.verdict.review{background:var(--review-bg);color:var(--review)}.verdict.deprecated{background:var(--deprecated-bg);color:var(--deprecated)}.verdict.ok{background:var(--fix-bg);color:var(--fix)}
.stats{display:grid;grid-template-columns:repeat(auto-fit,minmax(150px,1fr));gap:10px}.stat{background:var(--panel);border:1px solid var(--line);border-radius:10px;padding:12px 14px;display:flex;flex-direction:column}
.stat .num{font-size:28px;font-weight:700;font-variant-numeric:tabular-nums}.stat .label{font-weight:600}.stat .sub{color:var(--muted);font-size:13px}
.stat.breaks .num{color:var(--breaks)}.stat.review .num{color:var(--review)}.stat.deprecated .num{color:var(--deprecated)}.stat.fix .num{color:var(--fix)}
.legend{color:var(--muted);font-size:14px;margin:12px 0 0;padding-left:18px}
details{background:var(--panel);border:1px solid var(--line);border-radius:10px;margin:0 0 10px}summary{cursor:pointer;padding:12px 14px;display:flex;gap:10px;align-items:baseline;flex-wrap:wrap;list-style:none}summary::-webkit-details-marker{display:none}
.badge{font-size:12px;font-weight:700;border-radius:999px;padding:2px 9px;white-space:nowrap}.badge.breaks{background:var(--breaks-bg);color:var(--breaks)}.badge.review{background:var(--review-bg);color:var(--review)}.badge.deprecated{background:var(--deprecated-bg);color:var(--deprecated)}.badge.fix{background:var(--fix-bg);color:var(--fix)}
.title{font-weight:600;flex:1 1 240px}.count{color:var(--muted);font-variant-numeric:tabular-nums}.body{padding:0 14px 14px;border-top:1px solid var(--line)}.body p{margin:10px 0}
ul.loc{margin:8px 0 0;padding:0;list-style:none;font-size:13px}ul.loc li{padding:5px 0;border-top:1px dashed var(--line);overflow-wrap:anywhere}code{font:12.5px/1.4 ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}
.scroll{overflow-x:auto}table{border-collapse:collapse;width:100%;background:var(--panel);border:1px solid var(--line);border-radius:10px}th,td{text-align:left;padding:8px 10px;border-bottom:1px solid var(--line);font-size:14px}th{color:var(--muted);font-weight:600}.n{text-align:right;font-variant-numeric:tabular-nums}
ul.how{padding-left:18px;color:var(--muted)}footer{margin-top:40px;color:var(--muted);font-size:13px;border-top:1px solid var(--line);padding-top:14px}a{color:var(--accent)}.empty{color:var(--muted)}
</style>
</head>
<body>
<main>
<h1>PHP {$e($report->targetPhp)} upgrade report: {$e($p->name)}</h1>
<p class="meta">{$e($p->type)}{$e($p->version ? ' ' . $p->version : '')} · {$e((string) count($p->phpFiles))} PHP files · checked {$e($report->generatedAt->format('j M Y'))}</p>
<div class="verdict {$severityClass}">{$e($report->verdict())}</div>
<div class="stats">{$stats}</div>
<ul class="legend"><li><b>Breaks</b>: fails on PHP {$e($report->targetPhp)}; visitors usually see a "critical error" page.</li><li><b>Check</b>: can fail depending on input; needs a person to look at it.</li><li><b>Deprecated</b>: still works, but logs notices and will break in a later PHP version.</li></ul>
<h2>Issues in the project's own code</h2>
{$groups}
{$old}
{$libraries}
<h2>How this was checked</h2>
<ul class="how">
<li>Target PHP {$e($report->targetPhp)}. The code must keep running on PHP {$e($report->minPhp)} ({$e($report->minPhpSource)}), so automatic fixes never use newer syntax than that.</li>
<li>Every file was compiled with PHP {$e($report->lintPhp)}. No project code was executed.</li>
<li>Tools: {$e($tools)}.</li>
<li>Static checks cannot see problems that depend on runtime data, such as a function receiving null or a string where it now requires an array. Test the upgraded code on a staging site with debug logging on.</li>
</ul>
{$footer}
</main>
</body>
</html>

HTML;
    }

    /**
     * @param array{code: string, severity: string, findings: list<Finding>} $group
     */
    private function group(array $group, string $targetPhp): string
    {
        $findings = $group['findings'];
        $fixable = count(array_filter($findings, static fn (Finding $f): bool => $f->fixable));
        $fix = Explanations::fix($group['code']);

        $items = '';
        foreach (array_slice($findings, 0, self::MAX_LOCATIONS) as $finding) {
            $items .= sprintf(
                '<li><code>%s:%d</code>%s<br>%s</li>',
                $this->e($finding->file),
                $finding->line,
                $finding->fixable ? ' <span class="badge fix">auto</span>' : '',
                $this->e($finding->message),
            );
        }
        if (count($findings) > self::MAX_LOCATIONS) {
            $items .= sprintf('<li>…and %d more. The JSON report lists all of them.</li>', count($findings) - self::MAX_LOCATIONS);
        }

        return sprintf(
            '<details><summary><span class="badge %s">%s</span><span class="title">%s</span><span class="count">%d found</span>%s</summary><div class="body"><p>%s</p>%s<ul class="loc">%s</ul></div></details>',
            $group['severity'],
            $this->e(Explanations::severityLabel($group['severity'])),
            $this->e(Explanations::title($group['code'], $findings[0])),
            count($findings),
            $fixable > 0 ? sprintf('<span class="badge fix">%s auto-fixable</span>', $fixable === count($findings) ? 'all' : $fixable . ' of ' . count($findings)) : '',
            $this->e(Explanations::meaning($group['code'], $group['severity'], $targetPhp)),
            $fix !== null ? '<p><b>Fix:</b> ' . $this->e($fix) . '</p>' : '',
            $items,
        );
    }

    private function e(string $value): string
    {
        return htmlspecialchars($value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
    }
}
